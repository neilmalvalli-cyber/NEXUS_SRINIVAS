// ---------------------------------------------------------------- results

type result struct {
	ID       string
	Title    string
	Expected string
	Method   string
	Pass     bool
	Notes    []string
	Duration time.Duration
}

var (
	resMu   sync.Mutex
	results []*result
	full    = os.Getenv("KVDB_SCENARIOS") == "full"
	bins    struct {
		once          sync.Once
		dir           string
		kvdb, torture string
		err           error
	}
)

// sc is the handle a scenario body uses to log diagnostics.
type sc struct {
	t *testing.T
	r *result
}

func (s *sc) note(format string, a ...any) {
	msg := fmt.Sprintf(format, a...)
	s.r.Notes = append(s.r.Notes, msg)
	s.t.Log(msg)
}

func (s *sc) failf(format string, a ...any) {
	s.t.Helper()
	msg := fmt.Sprintf(format, a...)
	s.r.Notes = append(s.r.Notes, "FAIL: "+msg)
	s.t.Errorf("%s", msg)
}

func (s *sc) fatalf(format string, a ...any) {
	s.t.Helper()
	msg := fmt.Sprintf(format, a...)
	s.r.Notes = append(s.r.Notes, "FAIL: "+msg)
	s.t.Fatalf("%s", msg)
}

// scenario runs one official scenario as a subtest and records its result.
func scenario(t *testing.T, id, title, expected, method string, body func(s *sc)) {
	t.Run(id, func(t *testing.T) {
		r := &result{ID: id, Title: title, Expected: expected, Method: method}
		t.Logf("%s: %s\n  expected: %s\n  method: %s", id, title, expected, method)
		start := time.Now()
		defer func() {
			r.Duration = time.Since(start)
			r.Pass = !t.Failed()
			resMu.Lock()
			results = append(results, r)
			resMu.Unlock()
		}()
		body(&sc{t: t, r: r})
	})
}

func TestMain(m *testing.M) {
	code := m.Run()
	if p := os.Getenv("KVDB_SCENARIO_REPORT"); p != "" {
		if err := writeReport(p); err != nil {
			fmt.Fprintln(os.Stderr, "scenario report:", err)
			code = 1
		}
	}
	if p := os.Getenv("KVDB_SCENARIO_JSON"); p != "" {
		if err := writeJSONReport(p); err != nil {
			fmt.Fprintln(os.Stderr, "scenario JSON report:", err)
			code = 1
		}
	}
	if bins.dir != "" {
		os.RemoveAll(bins.dir)
	}
	os.Exit(code)
}

func writeReport(path string) error {
	path = fromRoot(path)
	resMu.Lock()
	defer resMu.Unlock()
	sort.Slice(results, func(i, j int) bool { return scenarioOrder(results[i].ID) < scenarioOrder(results[j].ID) })
	var b strings.Builder
	host, _ := os.Hostname()
	_ = host
	mode := "quick"
	if full {
		mode = "full (KVDB_SCENARIOS=full)"
	}
	pass := 0
	for _, r := range results {
		if r.Pass {
			pass++
		}
	}
	fmt.Fprintf(&b, "# Official scenario results\n\nGenerated by `go test ./src/scenarios` on %s, %s/%s, %d CPUs, Go %s. Mode: %s.\n\n",
		time.Now().Format("2006-01-02 15:04 MST"), runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), runtime.Version(), mode)
	fmt.Fprintf(&b, "**%d of %d scenarios passed.**\n\n", pass, len(results))
	b.WriteString("| # | Scenario | Expected | How it was executed | Result | Time | Diagnostics |\n|---|---|---|---|---|---|---|\n")
	esc := func(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }
	for _, r := range results {
		v := "PASS"
		if !r.Pass {
			v = "**FAIL**"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %.2fs | %s |\n", r.ID, esc(r.Title), esc(r.Expected), esc(r.Method), v,
			r.Duration.Seconds(), esc(strings.Join(r.Notes, "; ")))
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// writeJSONReport writes the same results as writeReport, machine-readable
// (KVDB_SCENARIO_JSON=path), for the dashboard's Judge Readiness page.
// Only scenarios that actually ran are listed; nothing is filled in.
func writeJSONReport(path string) error {
	path = fromRoot(path)
	resMu.Lock()
	defer resMu.Unlock()
	sort.Slice(results, func(i, j int) bool { return scenarioOrder(results[i].ID) < scenarioOrder(results[j].ID) })
	type item struct {
		ID         string   `json:"id"`
		Title      string   `json:"title"`
		Expected   string   `json:"expected"`
		Method     string   `json:"method"`
		Pass       bool     `json:"pass"`
		DurationMs float64  `json:"duration_ms"`
		Notes      []string `json:"notes"`
	}
	mode := "quick"
	if full {
		mode = "full"
	}
	out := struct {
		Generated string `json:"generated"`
		GOOS      string `json:"goos"`
		GOARCH    string `json:"goarch"`
		CPUs      int    `json:"cpus"`
		Go        string `json:"go"`
		Mode      string `json:"mode"`
		Results   []item `json:"results"`
	}{time.Now().Format(time.RFC3339), runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), runtime.Version(), mode, []item{}}
	for _, r := range results {
		notes := r.Notes
		if notes == nil {
			notes = []string{}
		}
		out.Results = append(out.Results, item{r.ID, r.Title, r.Expected, r.Method, r.Pass, float64(r.Duration.Microseconds()) / 1000, notes})
	}
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

func scenarioOrder(id string) string {
	if len(id) >= 2 && id[1] >= '0' && id[1] <= '9' {
		return fmt.Sprintf("%c%02s", id[0], strings.SplitN(id[1:], "_", 2)[0])
	}
	return id
}

// ---------------------------------------------------------------- engine helpers

var opts = recovery.DefaultOptions

func openLog(t *testing.T, fsys fileio.FS, db string, maxBytes int64) *storage.Log {
	t.Helper()
	l, err := storage.OpenWith(fsys, db, storage.Config{Recovery: opts, MaxBytes: maxBytes, AutoCompact: true})
	if err != nil {
		t.Fatalf("open %s: %v", db, err)
	}
	return l
}

func P(k, v string) format.Entry {
	return format.Entry{Op: format.OpPut, Key: []byte(k), Value: []byte(v)}
}
func D(k string) format.Entry { return format.Entry{Op: format.OpDelete, Key: []byte(k)} }

func commit(t *testing.T, l *storage.Log, es ...format.Entry) {
	t.Helper()
	if err := l.Commit(es); err != nil {
		t.Fatalf("commit: %v", err)
	}
}

// state reopens db with the real file system (running recovery), verifies the
// whole file (Verify: every CRC, sequence, index == rescan) and returns the
// contents. Any failure to open is a scenario failure: open() must never
// fail on a file the database produced.
func state(t *testing.T, db string) map[string]string {
	t.Helper()
	l, err := storage.OpenWith(fileio.OS{}, db, storage.Config{Recovery: opts, AutoCompact: false})
	if err != nil {
		t.Fatalf("reopen after crash failed: %v", err)
	}
	defer l.Close()
	if _, err := l.Verify(); err != nil {
		t.Fatalf("verify after reopen: %v", err)
	}
	m := map[string]string{}
	if err := l.Range(func(k, v []byte) error { m[string(k)] = string(v); return nil }); err != nil {
		t.Fatalf("range: %v", err)
	}
	return m
}

func newDB(t *testing.T, es ...format.Entry) string {
	t.Helper()
	db := filepath.Join(t.TempDir(), "db.kv")
	l := openLog(t, fileio.OS{}, db, 0)
	if len(es) > 0 {
		commit(t, l, es...)
	}
	if err := l.Close(); err != nil {
		t.Fatal(err)
	}
	return db
}

func same(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if w, ok := b[k]; !ok || w != v {
			return false
		}
	}
	return true
}

func with(m map[string]string, kv ...string) map[string]string {
	out := map[string]string{}
	for k, v := range m {
		out[k] = v
	}
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] == "<del>" {
			delete(out, kv[i])
		} else {
			out[kv[i]] = kv[i+1]
		}
	}
	return out
}

func fileSize(t *testing.T, p string) int64 {
	t.Helper()
	fi, err := os.Stat(p)
	if err != nil {
		t.Fatal(err)
	}
	return fi.Size()
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

// leftovers lists temporary files next to db.
func leftovers(db string) []string {
	var out []string
	for _, s := range []string{recovery.SuffixCompact, recovery.SuffixOld, recovery.SuffixNew} {
		if exists(db + s) {
			out = append(out, filepath.Base(db+s))
		}
	}
	return out
}

// crashAt runs fn on a fresh faultfs-backed handle with one crash rule and
// reports whether the crash fired. The handle is abandoned like a killed
// process: faultfs closes its files without any cleanup code running.
func crashAt(t *testing.T, db string, maxBytes int64, r faultfs.Rule, fn func(l *storage.Log)) (crashed bool, ev []faultfs.Event) {
	t.Helper()
	ffs := faultfs.New(fileio.OS{})
	l := openLog(t, ffs, db, maxBytes)
	ffs.Add(r)
	crashed = faultfs.RunUntilCrash(func() { fn(l) })
	if !crashed {
		l.Close()
	}
	return crashed, ffs.Events()
}

// countEvents runs fn on a copy-free faultfs handle and returns the events
// it produced (no faults), for sweeps over "every operation of X".
func countEvents(t *testing.T, db string, maxBytes int64, fn func(l *storage.Log)) []faultfs.Event {
	t.Helper()
	ffs := faultfs.New(fileio.OS{})
	l := openLog(t, ffs, db, maxBytes)
	base := len(ffs.Events())
	fn(l)
	ev := ffs.Events()[base:]
	l.Close()
	return ev
}

// copyDB copies a database file to a fresh directory.
func copyDB(t *testing.T, src string) string {
	t.Helper()
	b, err := os.ReadFile(src)
	if err != nil {
		t.Fatal(err)
	}
	dst := filepath.Join(t.TempDir(), "db.kv")
	if err := os.WriteFile(dst, b, 0o644); err != nil {
		t.Fatal(err)
	}
	return dst
}

// ---------------------------------------------------------------- binaries

func buildBinaries(t *testing.T) (kvdbBin, tortureBin string) {
	t.Helper()
	bins.once.Do(func() {
		dir, err := os.MkdirTemp("", "kvdb-scenario-bin")
		if err != nil {
			bins.err = err
			return
		}
		bins.dir = dir
		goBin := filepath.Join(runtime.GOROOT(), "bin", "go")
		root, err := moduleRoot()
		if err != nil {
			bins.err = err
			return
		}
		cmd := exec.Command(goBin, "build", "-o", dir+string(os.PathSeparator), "./src/cmd/kvdb", "./src/cmd/torture")
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			bins.err = fmt.Errorf("go build: %v\n%s", err, out)
			return
		}
		ext := ""
		if runtime.GOOS == "windows" {
			ext = ".exe"
		}
		bins.kvdb = filepath.Join(dir, "kvdb"+ext)
		bins.torture = filepath.Join(dir, "torture"+ext)
	})
	if bins.err != nil {
		t.Fatalf("building binaries: %v", bins.err)
	}
	return bins.kvdb, bins.torture
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if exists(filepath.Join(dir, "go.mod")) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}

// tortureSummary is the part of torture's report.json the scenarios read.
type tortureSummary struct {
	Passed             int     `json:"passed"`
	Failed             int     `json:"failed"`
	Acked              int     `json:"acked_writes"`
	Rejected           int     `json:"rejected_writes"`
	Unknown            int     `json:"unknown_writes"`
	FullErrors         int     `json:"full_errors"`
	KillsMidWrite      int     `json:"kills_with_write_in_flight"`
	KillsMidCompaction int     `json:"kills_with_compaction_in_flight"`
	TornTails          int     `json:"recoveries_discarding_torn_tail"`
	AuthorityRules     int     `json:"recoveries_resolving_interrupted_compaction"`
	RecoveryKills      int     `json:"recovery_kills"`
	RecoveryLanded     int     `json:"recovery_kills_landed"`
	MaxOpenMs          float64 `json:"max_open_recovery_ms"`
	ElapsedSec         float64 `json:"elapsed_sec"`
	ToolError          string  `json:"tool_error"`
}

// runTorture runs the torture tool against the kvdb binary and records its
// summary. The scenario passes only if every iteration passed.
func runTorture(s *sc, mode string, iterations int, seed int64, extra ...string) tortureSummary {
	s.t.Helper()
	kv, tt := buildBinaries(s.t)
	dir := filepath.Join(s.t.TempDir(), "run")
	args := append([]string{"--iterations", fmt.Sprint(iterations), "--seed", fmt.Sprint(seed), "--mode", mode,
		"--kvdb", kv, "--dir", dir, "--quiet"}, extra...)
	cmd := exec.Command(tt, args...)
	out, err := cmd.CombinedOutput()
	var sum tortureSummary
	if b, rerr := os.ReadFile(filepath.Join(dir, "report.json")); rerr == nil {
		json.Unmarshal(b, &sum)
	}
	s.note("torture --mode %s --seed %d --iterations %d: passed %d/%d, acked %d, rejected %d, unknown %d, kills with a write in flight %d, compaction in flight %d, torn tails discarded %d, interrupted compactions resolved %d, recovery kills landed %d/%d, full errors %d, max open %.1f ms, %.1fs",
		mode, seed, iterations, sum.Passed, iterations, sum.Acked, sum.Rejected, sum.Unknown, sum.KillsMidWrite, sum.KillsMidCompaction,
		sum.TornTails, sum.AuthorityRules, sum.RecoveryLanded, sum.RecoveryKills, sum.FullErrors, sum.MaxOpenMs, sum.ElapsedSec)
	if err != nil || sum.Passed != iterations {
		tail := string(out)
		if len(tail) > 3000 {
			tail = tail[len(tail)-3000:]
		}
		s.failf("torture failed (%v):\n%s", err, tail)
	}
	return sum
}

