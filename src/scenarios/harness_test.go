// serveProc is a running `kvdb serve` child.
type serveProc struct {
	cmd *exec.Cmd
	in  io.WriteCloser
	out *bufio.Reader
}

func startServe(t *testing.T, db string, args ...string) *serveProc {
	t.Helper()
	kv, _ := buildBinaries(t)
	cmd := exec.Command(kv, append([]string{"serve", db}, args...)...)
	in, err := cmd.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	out, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	return &serveProc{cmd: cmd, in: in, out: bufio.NewReaderSize(out, 1<<20)}
}

func (p *serveProc) send(t *testing.T, s string) {
	t.Helper()
	if _, err := io.WriteString(p.in, s); err != nil {
		t.Fatalf("writing to serve: %v", err)
	}
}

func (p *serveProc) reply(t *testing.T) string {
	t.Helper()
	l, err := p.out.ReadString('\n')
	if err != nil {
		t.Fatalf("reading serve reply: %v", err)
	}
	return strings.TrimRight(l, "\r\n")
}

// kill terminates the child with no warning (TerminateProcess / SIGKILL).
func (p *serveProc) kill() {
	p.cmd.Process.Kill()
	io.Copy(io.Discard, p.out)
	p.cmd.Wait()
}

func runKvdb(t *testing.T, args ...string) (string, string, error) {
	t.Helper()
	kv, _ := buildBinaries(t)
	cmd := exec.Command(kv, args...)
	var o, e strings.Builder
	cmd.Stdout, cmd.Stderr = &o, &e
	err := cmd.Run()
	return o.String(), e.String(), err
}

var execCommand = exec.Command

// fromRoot resolves a relative report path against the module root: `go
// test` runs in the package directory, but paths in the README are given
// from the repository root.
func fromRoot(p string) string {
	if filepath.IsAbs(p) {
		return p
	}
	if root, err := moduleRoot(); err == nil {
		return filepath.Join(root, p)
	}
	return p
}
